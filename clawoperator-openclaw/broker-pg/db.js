'use strict';

const fs = require('fs');
const { Pool } = require('pg');

function backendDomain(host) {
  const dot = (host || '').indexOf('.');
  return dot === -1 ? '' : host.slice(dot + 1);
}

async function createDb() {
  const ssl = process.env.PGSSL_CA_PATH
    ? { ca: fs.readFileSync(process.env.PGSSL_CA_PATH, 'utf8'), rejectUnauthorized: true }
    : process.env.PGSSL === 'true' ? { rejectUnauthorized: true } : false;
  const pool = new Pool({
    host: process.env.PGHOST,
    port: Number(process.env.PGPORT || 5432),
    database: process.env.PGDATABASE,
    user: process.env.PGUSER,
    password: process.env.PGPASSWORD,
    max: 5,
    connectionTimeoutMillis: 5000,
    idleTimeoutMillis: 30000,
    ssl,
  });
  pool.on('error', (error) => {
    console.error('PostgreSQL idle connection error:', error.message);
  });

  // Concurrent broker replicas may start together. PostgreSQL serializes this
  // schema initialization with an advisory lock on a single connection.
  const init = await pool.connect();
  try {
    await init.query('SELECT pg_advisory_lock(73194621)');
    await init.query(`
      CREATE TABLE IF NOT EXISTS routes (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        public_host TEXT NOT NULL UNIQUE,
        backend_host TEXT NOT NULL,
        enabled BOOLEAN NOT NULL DEFAULT TRUE,
        namespace TEXT NOT NULL DEFAULT '',
        token_fragment TEXT NOT NULL DEFAULT ''
      );
      CREATE TABLE IF NOT EXISTS assignments (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        cookie_value UUID NOT NULL UNIQUE,
        route_id BIGINT NOT NULL UNIQUE REFERENCES routes(id) ON DELETE CASCADE,
        assigned_at TIMESTAMPTZ NOT NULL DEFAULT now()
      );
      CREATE TABLE IF NOT EXISTS audiences (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        audience_id TEXT,
        started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        active BOOLEAN NOT NULL DEFAULT TRUE
      );
      CREATE INDEX IF NOT EXISTS routes_namespace_domain_idx
        ON routes(namespace, backend_host);
    `);
  } finally {
    await init.query('SELECT pg_advisory_unlock(73194621)').catch(() => {});
    init.release();
  }

  async function transaction(work) {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      const result = await work(client);
      await client.query('COMMIT');
      return result;
    } catch (error) {
      await client.query('ROLLBACK').catch(() => {});
      throw error;
    } finally {
      client.release();
    }
  }

  async function insertRoute(client, route) {
    await client.query(
      `INSERT INTO routes (public_host, backend_host, enabled, namespace, token_fragment)
       VALUES ($1, $2, $3, $4, $5)`,
      [route.public_host, route.backend_host, Boolean(route.enabled), route.namespace || '', route.token_fragment || '']
    );
  }

  return {
    async loadRoutes(routes, audienceId) {
      return transaction(async (client) => {
        await client.query('DELETE FROM assignments');
        await client.query('DELETE FROM routes');
        await client.query('UPDATE audiences SET active = FALSE');
        for (const route of routes) await insertRoute(client, route);
        if (audienceId) {
          await client.query('INSERT INTO audiences (audience_id) VALUES ($1)', [audienceId]);
        }
      });
    },

    async reloadRoutes(routes) {
      return transaction(async (client) => {
        // Serialize admin reloads. Claims still use row locks and unique
        // route_id constraints, so assignments remain exclusive.
        await client.query('SELECT pg_advisory_xact_lock(73194622)');
        const audience = await client.query(
          'SELECT id FROM audiences WHERE active = TRUE ORDER BY id DESC LIMIT 1'
        );
        if (audience.rows.length === 0 && routes.length > 0) {
          const match = routes[0].public_host.match(/^claw-([a-z0-9]+)-/);
          if (match) {
            await client.query('INSERT INTO audiences (audience_id) VALUES ($1)', [match[1]]);
          }
        }
        for (const route of routes) {
          const namespace = route.namespace || '';
          const domain = backendDomain(route.backend_host);
          const existing = await client.query(
            `SELECT id, public_host FROM routes
             WHERE namespace = $1 AND substr(backend_host, strpos(backend_host, '.') + 1) = $2
             FOR UPDATE`,
            [namespace, domain]
          );
          if (existing.rows.length && existing.rows[0].public_host === route.public_host) {
            await client.query(
              `UPDATE routes SET backend_host = $1, enabled = $2, token_fragment = $3
               WHERE id = $4`,
              [route.backend_host, Boolean(route.enabled), route.token_fragment || '', existing.rows[0].id]
            );
            continue;
          }
          if (existing.rows.length) {
            await client.query('DELETE FROM routes WHERE id = $1', [existing.rows[0].id]);
          }
          await insertRoute(client, route);
        }
      });
    },

    async assignRoute(cookieValue) {
      // A single statement claims one unlocked route. The unique route_id
      // constraint is a second guard against duplicate assignments.
      const result = await pool.query(
        `WITH candidate AS (
           SELECT r.id FROM routes r
           WHERE r.enabled = TRUE
             AND NOT EXISTS (SELECT 1 FROM assignments a WHERE a.route_id = r.id)
           ORDER BY r.id
           FOR UPDATE SKIP LOCKED
           LIMIT 1
         ), claimed AS (
           INSERT INTO assignments (cookie_value, route_id)
           SELECT $1::uuid, id FROM candidate
           ON CONFLICT (route_id) DO NOTHING
           RETURNING route_id
         )
         SELECT r.id, r.public_host, r.backend_host, r.token_fragment
         FROM claimed a JOIN routes r ON r.id = a.route_id`,
        [cookieValue]
      );
      return result.rows[0] || null;
    },

    async findAssignment(cookieValue) {
      if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(cookieValue)) {
        return null;
      }
      const result = await pool.query(
        `SELECT r.id, r.public_host, r.backend_host, r.token_fragment
         FROM assignments a JOIN routes r ON r.id = a.route_id
         WHERE a.cookie_value = $1::uuid`,
        [cookieValue]
      );
      return result.rows[0] || null;
    },

    async releaseRoute(routeId) {
      await pool.query('DELETE FROM assignments WHERE route_id = $1', [routeId]);
    },

    async resetAssignments() {
      await pool.query('DELETE FROM assignments');
    },

    async getAllRoutes() {
      const result = await pool.query('SELECT * FROM routes ORDER BY id');
      return result.rows;
    },

    async getRoutesWithStatus() {
      const result = await pool.query(
        `SELECT r.id, r.public_host, r.backend_host, r.enabled, r.namespace, r.token_fragment,
                CASE WHEN a.id IS NOT NULL THEN 1 ELSE 0 END AS assigned,
                a.assigned_at
         FROM routes r LEFT JOIN assignments a ON a.route_id = r.id ORDER BY r.id`
      );
      return result.rows;
    },

    async getStats() {
      const result = await pool.query(
        `SELECT
           (SELECT count(*)::int FROM routes WHERE enabled = TRUE) AS total,
           (SELECT count(*)::int FROM assignments a JOIN routes r ON r.id = a.route_id WHERE r.enabled = TRUE) AS assigned,
           (SELECT audience_id FROM audiences WHERE active = TRUE ORDER BY id DESC LIMIT 1) AS audience_id,
           (SELECT started_at FROM audiences WHERE active = TRUE ORDER BY id DESC LIMIT 1) AS audience_started`
      );
      const stats = result.rows[0];
      return { ...stats, available: stats.total - stats.assigned };
    },

    async close() {
      await pool.end();
    },
  };
}

module.exports = { createDb };
