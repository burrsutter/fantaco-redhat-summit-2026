#   - 6-inject-enterprise-skills.sh (skill injection)
#
# Usage:
#   ./audience-reset.sh              # reset all agentic-user namespaces on cluster
#   ./audience-reset.sh 1 5          # reset user1 through user5
#   ./audience-reset.sh 3            # just user3
#
