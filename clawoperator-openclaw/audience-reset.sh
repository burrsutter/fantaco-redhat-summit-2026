    - name: gcp-vertex
      type: gcp
      secretRef:
        - name: gcp-service-account
          key: sa-key.json
      domain: .googleapis.com
      provider: google
      gcp:
        project: ${GOOGLE_CLOUD_PROJECT:-}
        location: ${GOOGLE_CLOUD_LOCATION:-us-central1}
CRED
        ;;
      openrouter)
        cat <<CRED
    - name: openrouter
      type: bearer
      secretRef:
        - name: openrouter-api-key
          key: api-key
      domain: openrouter.ai
      provider: openai
CRED
