        ;;
      anthropic)
        cat <<CRED
    - name: anthropic
      type: apiKey
      secretRef:
        - name: anthropic-api-key
          key: api-key
      provider: anthropic
CRED
        ;;
      openai)
        cat <<CRED
    - name: openai
      type: apiKey
      secretRef:
        - name: openai-api-key
          key: api-key
      provider: openai
CRED
        ;;
      gcp)
