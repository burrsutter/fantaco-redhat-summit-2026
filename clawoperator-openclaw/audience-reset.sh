  OTEL_BACKEND="MLflow"
  OTEL_ENDPOINT="${MLFLOW_INTERNAL_URL}/v1/traces"
  OTEL_HEADERS="x-mlflow-experiment-id=${EXPERIMENT_ID}"
  OTEL_INTERNAL_URL="${MLFLOW_INTERNAL_URL}"
